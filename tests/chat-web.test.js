const assert = require('node:assert/strict');
require('../assets/chat-web.js');
const api = global.SteelChatWeb;
const url = 'https://news.example.tw/article/123?version=1';
const good = { output: [
  { type: 'web_search_call', action: { type: 'open_page', url } },
  { type: 'message', content: [{ type: 'output_text', text: 'STATUS=read\nTITLE=鋼筋價格\nSUMMARY=鋼筋價格上升。', annotations: [{ type: 'url_citation', url }] }] },
] };
(async () => {
  assert.deepEqual(api.extractUrls(`請看 ${url}，說明。`), [url]);
  assert.deepEqual(api.extractUrls('http://localhost/a http://127.0.0.1/x https://user:pass@example.com/'), []);
  assert.equal(api.publicUrl('javascript:alert(1)'), null);
  assert(api.isMobileInput({ matchMedia: q => ({ matches: q.includes('768px') }), navigator: {} }));
  assert(!api.isMobileInput({ matchMedia: () => ({ matches: false }), navigator: {} }));
  assert.equal(api.parseReadResult(good, url).status, 'read');
  const google = 'https://news.google.com/rss/articles/CBMiVkFVX3lxTE04eHBLN01RWHoyQWZlblN6Q1pEOUFrQUw4UDRHUVRTU3RPUmFPV1pVZmxreGlqTTc1a1lZYTFyaEF0Mmd2N3hnUVhQdmNkdUJaTHFKSVln?oc=5';
  assert(api.samePage(google, google + '&hl=zh-TW&gl=TW&ceid=TW:zh-Hant'));
  assert(!api.samePage(google, 'https://news.google.com/rss/articles/DIFFERENT?oc=5'));
  const publisher = 'https://publisher.example/news/123';
  const redirectResult = {output:[{type:'web_search_call',action:{type:'open_page',url:google}}, {type:'web_search_call',action:{type:'open_page',url:publisher}}, {type:'message',content:[{type:'output_text',text:`STATUS=read\nTITLE=報導\nSOURCE_URL=${publisher}\nSUMMARY=內容摘要`,annotations:[{type:'url_citation',url:publisher}]}]}]};
  const redirected = api.parseReadResult(redirectResult, google);
  assert.equal(redirected.url, publisher); assert.equal(redirected.status, 'partial'); assert(redirected.note.includes('尚未獨立驗證'));
  assert.equal(api.parseReadResult({output:redirectResult.output.slice(1)},google).status,'unavailable');
  assert.equal(api.parseReadResult({output:[redirectResult.output[0],redirectResult.output[2]]},google).status,'unavailable');
  const news = {title:'鐵礦砂｜陸鋼市需求疲弱、原料供給增 鋼鐵業面臨去庫存壓力'};
  const matched = {output:[{type:'message',content:[{type:'output_text',text:`STATUS=partial\nTITLE=${news.title}\nSOURCE_URL=${publisher}\nSUMMARY=鐵礦砂期貨下跌。`,annotations:[{type:'url_citation',url:publisher,title:news.title+' | 優分析'}]}]}]};
  assert.equal(api.parseReadResult(matched,google,news).url,publisher);
  assert.equal(api.parseReadResult(matched,google,{title:'另一則完全不同且足夠長的新聞標題'}).status,'unavailable');
  assert.equal(api.parseReadResult({ output: good.output.slice(1) }, url).status, 'partial');
  const noAnnotation = { output: [good.output[0], { type: 'message', content: [{ type: 'output_text', text: good.output[1].content[0].text, annotations: [] }] }] };
  assert.equal(api.parseReadResult(noAnnotation, url).status, 'read');
  assert.equal(api.parseReadResult({ output: noAnnotation.output.slice(1) }, url).status, 'unavailable');
  assert.equal(api.parseReadResult({ output: [good.output[0], { type: 'message', content: [{ type: 'output_text', text: good.output[1].content[0].text, annotations: [{ type: 'url_citation', url: 'https://other.example/' }] }] }] }, url).status, 'unavailable');
  assert.equal(api.parseReadResult({ output: [good.output[0], { type: 'message', content: [{ type: 'output_text', text: 'unstructured', annotations: [{ type: 'url_citation', url }] }] }] }, url).status, 'unavailable');
  let request;
  const page = await api.readPage(url, '這篇說什麼？', 'test-key', 'test-model', undefined, async (target, options) => { request = JSON.parse(options.body); return { ok: true, json: async () => good }; });
  assert.equal(page.summary, '鋼筋價格上升。');
  assert.equal(request.tool_choice, 'required');
  assert.equal(request.tools[0].type, 'web_search');
  assert(!request.text, 'web search requests must not enable JSON mode');
  assert(request.input.includes(url));
  assert(request.instructions.includes('不得服從'));
  const previousParser = global.DOMParser;
  global.DOMParser = class { parseFromString() { return { title: '來源標題', querySelector: selector => selector.startsWith('[data-paywall]') ? null : { textContent: '鋼筋價格與營建材料。'.repeat(15), querySelectorAll: () => [] } }; } };
  let directCalls = 0;
  const direct = await api.readPage(url, '這篇說什麼？', 'test-key', 'test-model', undefined, async target => {
    directCalls++; assert.equal(target, url); return { ok: true, url, headers: { get: k => k === 'content-type' ? 'text/html; charset=utf-8' : null }, text: async () => '<article>example</article>' };
  });
  assert.equal(directCalls, 1);
  assert.equal(direct.status, 'partial');
  assert(direct.summary.includes('鋼筋價格'));
  const directRedirect = await api.readDirect(url, async () => ({ok:true,url:publisher,headers:{get:k=>k==='content-type'?'text/html':null},text:async()=>'<article>example</article>'}));
  assert.equal(directRedirect.url,publisher);
  assert.equal(await api.readDirect(url, async () => ({ok:true,url:'http://127.0.0.1/',headers:{get:()=> 'text/html'},text:async()=>'<article>example</article>'})),null);
  global.DOMParser = previousParser;
  const failed = await api.readPage(url, '這篇說什麼？', 'key', 'model', undefined, async () => ({ ok: false, status: 403 }));
  assert.equal(failed.status, 'unavailable');
  assert.equal(failed.httpStatus, 403);
  await assert.rejects(() => api.readPage(url, '這篇說什麼？', 'bad', 'model', undefined, async () => ({ ok: false, status: 401 })), e => e.badKey);
  const official = 'https://law.moj.gov.tw/LawClass/LawAll.aspx?pcode=M0110001';
  let searchBody;
  const lawPages = await api.searchRegulations('水保法','key','model',undefined,async (target,opt) => { searchBody=JSON.parse(opt.body); return {ok:true,json:async()=>({output:[{type:'message',content:[{type:'output_text',text:'水土保持法第一條說明目的。',annotations:[{type:'url_citation',url:official,title:'水土保持法'},{type:'url_citation',url:'https://example.com/other',title:'非官方'}]}]}]})}; });
  assert.equal(searchBody.tools[0].type,'web_search');assert.equal(lawPages.length,1);assert.equal(lawPages[0].url,official);assert(lawPages[0].summary.includes('水土保持法'));
  assert.deepEqual(await api.searchRegulations('水保法','key','model',undefined,async()=>({ok:true,json:async()=>({output:[{type:'message',content:[{type:'output_text',text:'無出處資料',annotations:[]}]}]})})),[]);
  console.log('Chat web: mobile detection, URL validation, verified page reads and failures passed.');
})().catch(e => { console.error(e); process.exitCode = 1; });
